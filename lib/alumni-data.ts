export function extractBatchYear(batchStr?: string): number {
  if (!batchStr) return 0;
  // Match 4-digit year like 2022, 2013, 1995
  const fourDigit = batchStr.match(/\b(19\d{2}|20\d{2})\b/);
  if (fourDigit) return parseInt(fourDigit[1], 10);
  
  // Match 2-digit year with apostrophe or quote like '22, '19
  const twoDigit = batchStr.match(/['’](\d{2})\b/);
  if (twoDigit) {
    const yr = parseInt(twoDigit[1], 10);
    return yr >= 60 ? 1900 + yr : 2000 + yr;
  }
  
  // Fallback to any 2 digits
  const anyDigits = batchStr.match(/\b(\d{2})\b/);
  if (anyDigits) {
    const yr = parseInt(anyDigits[1], 10);
    return yr >= 60 ? 1900 + yr : 2000 + yr;
  }
  return 0;
}

export function getRoleRank(roleStr?: string): number {
  if (!roleStr) return 99;
  const r = roleStr.toLowerCase();
  if (r.includes("president") && !r.includes("vice")) return 1;
  if (r.includes("vice president") || r.includes("vp")) return 2;
  if (r.includes("general secretary") || r.includes("gs")) return 3;
  if (r.includes("joint secretary") || r.includes("ags") || r.includes("assistant general")) return 4;
  if (r.includes("organizing") || r.includes("organising")) return 5;
  if (r.includes("treasurer") || r.includes("finance")) return 6;
  if (r.includes("head") || r.includes("lead") || r.includes("director")) return 7;
  if (r.includes("secretary")) return 8;
  if (r.includes("executive")) return 9;
  return 10;
}

